async function openTools(page: Page) {
  if (!await page.locator('.v2-tool-controller').isVisible()) await page.locator('[data-action="open-tools"]').click()
}
async function runTask(page: Page, task: 'product' | 'shipping') {
  await openTools(page)
  await page.getByLabel('选择一键任务').selectOption(task)
  await page.locator('[data-action="run"]').click()
}
async function expectCompleted(page: Page) {
  await expect(page.locator('.v2-run-dock')).toContainText('已完成，保存状态核对通过')
  await openTools(page)
  await expect(page.getByTestId('run-status')).toHaveText('已完成，保存状态核对通过')
}

