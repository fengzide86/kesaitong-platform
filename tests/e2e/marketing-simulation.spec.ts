test('all six areas remain legible and locally scrollable on desktop and mobile', async ({ page }, testInfo) => {
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 980 })
    await page.goto('/demo')
    for (const area of ['home', 'inventory', 'templates', 'advertising', 'orders', 'warehouse']) {
      if (area === 'home') await page.locator('[data-action="home"]').click()
      else await page.locator(`[data-action="nav-${area}"]`).click()
      await expect(page.getByTestId('simulation')).toContainText('不影响真实平台')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
      await page.screenshot({ path: testInfo.outputPath(`simulation-${width}-${area}.png`), fullPage: true })
    }
    await page.locator('[data-action="nav-inventory"]').click()
    await page.locator('[data-action="new-product"]').click()
    for (const tab of ['important', 'variants', 'offer', 'compliance', 'images', 'description']) {
      await page.locator(`[data-action="tab-${tab}"]`).click()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
      await page.screenshot({ path: testInfo.outputPath(`simulation-${width}-product-${tab}.png`), fullPage: true })
    }
    await page.getByRole('button', { name: '返回库存' }).click()
    await page.locator('[data-action="fba-sample-product"]').click()
    await expect(page.getByRole('dialog')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`simulation-${width}-fba-dialog.png`), fullPage: true })
    await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
  }
})

