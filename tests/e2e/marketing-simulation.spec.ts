test('five DOM-driven tasks read back sample state without business or external network requests', async ({ page }) => {
  const remote: string[] = [], errors: string[] = []
  page.on('request', request => {
    const url = new URL(request.url())
    if (url.hostname !== '127.0.0.1' || url.pathname.startsWith('/api/')) remote.push(request.url())
  })
  page.on('pageerror', error => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/demo')
  for (const task of ['template', 'product', 'fba', 'advertising', 'shipping']) {
    await page.locator('#simulation-task').selectOption(task)
    await page.locator('[data-action="run"]').click()
    await expect(page.getByTestId('run-status')).toContainText('列表状态核对通过')
  }
  const snapshot = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), storageKey)
  expect(snapshot.products).toHaveLength(2)
  expect(snapshot.products[1]).toMatchObject({ brand: 'KST Sample', price: 19.9, quantity: 60, weight: .25, variant: '蓝色 / M', published: true })
  expect(snapshot.templates[1]).toMatchObject({ country: '美国', service: '标准配送', unit: 'kg', handling: 2, limit: 2, base: 3, perKg: 5 })
  expect(snapshot.products[0].delivery).toBe('FBA')
  expect(snapshot.campaigns[0]).toMatchObject({ productId: 'sample-product', budget: 10, bid: .5, targeting: '自动投放', status: '投放中' })
  expect(snapshot.orders[0]).toMatchObject({ warehouse: '已出库', status: '已发货', carrier: '中邮', tracking: 'SAMPLE-TRACK-001' })
  await expect(page.locator('table')).toContainText('已发货')
  await page.locator('[data-action="nav-advertising"]').click()
  await page.getByRole('button', { name: '查看广告组' }).click()
  await expect(page.getByRole('dialog')).toContainText('SAMPLE-BAG-BLUE')
  await expect(page.getByRole('dialog')).toContainText('SAMPLEASIN01')
  expect(remote).toEqual([])
  expect(errors).toEqual([])
})

test('pause, continue, stop and reset preserve only the expected local sample changes', async ({ page }) => {
  await page.goto('/demo')
  await page.evaluate(() => localStorage.setItem('unrelated-user-setting', 'keep-me'))
  await page.locator('[data-action="run"]').click()
  await expect(page.getByRole('button', { name: '暂停', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  await expect(page.getByTestId('run-status')).toContainText('已暂停')
  const before = await page.locator('.step-list').textContent()
  await page.waitForTimeout(1000)
  expect(await page.locator('.step-list').textContent()).toBe(before)
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await expect(page.getByTestId('run-status')).toContainText('列表状态核对通过')
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).products.length, storageKey)).toBe(2)
  await page.locator('#simulation-task').selectOption('template')
  await page.locator('[data-action="run"]').click()
  await page.getByRole('button', { name: '停止', exact: true }).click()
  await expect(page.getByTestId('run-status')).toContainText('已保存的样例变化保留')
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).products.length, storageKey)).toBe(2)
  await page.getByRole('button', { name: '重置全部样例' }).click()
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!).products.length, storageKey)).toBe(2)
  await page.getByRole('button', { name: '重置全部样例' }).click()
  await page.locator('[data-action="confirm-reset"]').click()
  expect(await page.evaluate(key => ({ sample: localStorage.getItem(key), other: localStorage.getItem('unrelated-user-setting') }), storageKey)).toEqual({ sample: null, other: 'keep-me' })
  await page.reload()
  await page.locator('[data-action="nav-inventory"]').click()
  await expect(page.locator('tr[data-product-id]')).toHaveCount(1)
})

