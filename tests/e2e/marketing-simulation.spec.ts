test('desktop/tablet/mobile pages and eight editor tabs have no document overflow and no business or external network', async ({ page }, testInfo) => {
  test.setTimeout(120_000)
  const remote: string[] = [], errors: string[] = []
  page.on('request', request => {
    const url = new URL(request.url())
    if (url.protocol === 'http:' || url.protocol === 'https:') {
      if (url.hostname !== '127.0.0.1' || url.pathname.startsWith('/api/') || url.pathname.includes('ECrossAmazon')) remote.push(request.url())
    }
  })
  page.on('pageerror', error => errors.push(error.message))
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 980 })
    for (const area of ['course', 'seller', 'inventory', 'category', 'orders', 'warehouse']) {
      await page.goto(`/demo?page=${area}`)
      await expect(page.getByTestId('simulation')).toContainText('独立模拟')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `${width}px ${area} document overflow`).toBe(true)
      await page.screenshot({ path: testInfo.outputPath(`v2-${width}-${area}.png`), fullPage: true })
    }
    await page.goto(`/demo?page=product&product=${bagId}`)
    for (const tab of editorTabs) {
      await page.locator(`[data-action="tab-${tab}"]`).click()
      await expect(page.locator(`[data-action="tab-${tab}"]`)).toHaveAttribute('aria-selected', 'true')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `${width}px editor ${tab} document overflow`).toBe(true)
      await page.screenshot({ path: testInfo.outputPath(`v2-${width}-product-${tab}.png`), fullPage: true })
    }
  }
  expect(remote).toEqual([])
  expect(errors).toEqual([])
})
